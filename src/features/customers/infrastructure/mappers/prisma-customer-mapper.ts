import type { Customer as PrismaCustomer } from "@/generated/prisma/client";
import type { Customer, CustomerType, GstTreatment, CustomerStatus } from "../../domain/entities/customer";

export const toDomainCustomer = (row: PrismaCustomer): Customer => ({
  id: row.id,
  organizationId: row.organizationId,
  name: row.name,
  customerType: row.customerType as CustomerType,
  gstTreatment: row.gstTreatment as GstTreatment,
  status: row.status as CustomerStatus,
  contactPerson: row.contactPerson,
  email: row.email,
  phone: row.phone,
  alternatePhone: row.alternatePhone,
  billingAddress: {
    addressLine1: row.billingAddressLine1 ?? "",
    addressLine2: row.billingAddressLine2,
    city: row.billingCity ?? "",
    state: row.billingState ?? "",
    pinCode: row.billingPinCode ?? "",
    country: row.billingCountry ?? "India",
  },
  shippingAddress: {
    addressLine1: row.shippingAddressLine1 ?? "",
    addressLine2: row.shippingAddressLine2,
    city: row.shippingCity ?? "",
    state: row.shippingState ?? "",
    pinCode: row.shippingPinCode ?? "",
    country: row.shippingCountry ?? "India",
  },
  sameAsBillingAddress: row.sameAsBillingAddress,
  gstin: row.gstin,
  pan: row.pan,
  currency: row.currency,
  placeOfSupply: row.placeOfSupply,
  paymentTerms: row.paymentTerms,
  creditLimit: row.creditLimit !== null ? Number(row.creditLimit) : null,
  defaultDiscount: row.defaultDiscount !== null ? Number(row.defaultDiscount) : null,
  defaultTaxPreference: row.defaultTaxPreference,
  priceList: row.priceList,
  internalNotes: row.internalNotes,
  tags: row.tags,
  createdAt: row.createdAt,
  updatedAt: row.updatedAt,
});
