export const filterCustomers = (
  customers: readonly Customer[],
  options: CustomerFilterOptions,
): Customer[] => {
  const query = options.query?.trim().toLowerCase() ?? "";
  const typeFilter = options.customerType;
  const statusFilter = options.status;

  return customers.filter((cust) => {
    // Type match
    if (typeFilter && typeFilter !== "All" && cust.customerType !== typeFilter) {
      return false;
    }

    // Status match
    if (statusFilter && statusFilter !== "All" && cust.status !== statusFilter) {
      return false;
    }

    // Search query matches: name, email, phone, contactPerson, gstin
    if (query) {
      const matchName = cust.name.toLowerCase().includes(query);
      const matchEmail = cust.email?.toLowerCase().includes(query) ?? false;
      const matchPhone = cust.phone?.replace(/[\s+-]/g, "").includes(query.replace(/[\s+-]/g, "")) ?? false;
      const matchContact = cust.contactPerson?.toLowerCase().includes(query) ?? false;
      const matchGstin = cust.gstin?.toLowerCase().includes(query) ?? false;

      if (!matchName && !matchEmail && !matchPhone && !matchContact && !matchGstin) {
        return false;
      }
    }

    return true;
  });
};
